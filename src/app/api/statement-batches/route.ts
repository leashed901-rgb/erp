import { NextRequest, NextResponse } from 'next/server';
import { supabaseAdmin, DEFAULT_TENANT_ID } from '@/lib/supabaseAdmin';
import { generateStatement } from '@/lib/customerStatements';
import type { StatementBatch } from '@/lib/arApLinkTypes';

const err = (code: string, message: string, status: number) =>
  NextResponse.json({ error: { code, message, requestId: crypto.randomUUID() } }, { status });

const toBatch = (r: Record<string, unknown>): StatementBatch => ({
  id: String(r.id),
  statementType: String(r.statement_type || ''),
  periodStart: String(r.period_start || ''),
  periodEnd: String(r.period_end || ''),
  customerFilter: (r.customer_filter as string) || null,
  customerIds: Array.isArray(r.customer_ids) ? (r.customer_ids as unknown[]).map(String) : [],
  status: String(r.status || ''),
  statementCount: Number(r.statement_count || 0),
  generatedAt: (r.generated_at as string) || null,
  sentAt: (r.sent_at as string) || null,
});

/** GET /api/statement-batches — statement batches, newest first. */
export async function GET() {
  const sb = supabaseAdmin();
  const { data, error } = await sb
    .from('acct_statement_batches')
    .select('*')
    .eq('tenant_id', DEFAULT_TENANT_ID)
    .order('created_at', { ascending: false })
    .limit(50);
  if (error) return err('INTERNAL', error.message, 500);
  return NextResponse.json({ data: (data || []).map(toBatch) });
}

/**
 * POST /api/statement-batches — generate statements for a period.
 * Body: { periodStart, periodEnd, customerIds? } — when customerIds is
 * omitted, every customer with an open invoice balance is included.
 * Each statement is generated by the same helper as the single generate,
 * linked to the batch; the batch row carries the count. Generation only —
 * sending is per statement, through /api/customer-statements/[id]/send.
 */
export async function POST(req: NextRequest) {
  let body: Record<string, unknown>;
  try { body = await req.json(); } catch { return err('VALIDATION', 'Invalid JSON', 400); }
  if (!body.periodStart || !body.periodEnd) return err('VALIDATION', 'periodStart and periodEnd are required', 400);
  const sb = supabaseAdmin();
  let customerIds: string[] = Array.isArray(body.customerIds) ? (body.customerIds as unknown[]).map(String) : [];
  if (!customerIds.length) {
    const { data: open } = await sb
      .from('acct_ar_invoices')
      .select('customer_id,total,amount_paid,amount_credited')
      .eq('tenant_id', DEFAULT_TENANT_ID)
      .not('status', 'in', '("void","draft","written_off","paid")');
    const byCustomer = new Map<string, number>();
    (open || []).forEach((r) => {
      const bal = Number(r.total || 0) - Number(r.amount_paid || 0) - Number(r.amount_credited || 0);
      byCustomer.set(r.customer_id, (byCustomer.get(r.customer_id) || 0) + bal);
    });
    customerIds = [...byCustomer.entries()].filter(([, bal]) => bal > 0).map(([id]) => id);
  }
  if (!customerIds.length) return err('VALIDATION', 'No customers with an open balance for this period', 400);
  const { data: batch, error: batchErr } = await sb.from('acct_statement_batches').insert({
    tenant_id: DEFAULT_TENANT_ID,
    statement_type: 'balance_forward',
    period_start: String(body.periodStart),
    period_end: String(body.periodEnd),
    customer_filter: Array.isArray(body.customerIds) ? 'selected' : 'open_balance',
    customer_ids: customerIds,
    status: 'draft',
    statement_count: 0,
  }).select('*').single();
  if (batchErr) return err('INTERNAL', batchErr.message, 500);
  let generated = 0;
  const failures: { customerId: string; error: string }[] = [];
  for (const customerId of customerIds) {
    try {
      await generateStatement(sb, customerId, String(body.periodStart), String(body.periodEnd), batch.id);
      generated += 1;
    } catch (e) {
      failures.push({ customerId, error: e instanceof Error ? e.message : 'generation failed' });
    }
  }
  // status is 'generated' only when every statement landed; a partial
  // batch stays 'draft' (the CHECK allows draft|generated|sent only)
  // and the failures ride in meta.
  await sb.from('acct_statement_batches').update({
    status: generated === customerIds.length ? 'generated' : 'draft',
    statement_count: generated,
    generated_at: new Date().toISOString(),
  }).eq('id', batch.id);
  const { data: after } = await sb.from('acct_statement_batches').select('*').eq('id', batch.id).single();
  return NextResponse.json({ data: toBatch(after), meta: { generated, failed: failures } }, { status: 201 });
}
